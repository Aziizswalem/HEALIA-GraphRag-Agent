from __future__ import annotations

"""Resolve slash-command shortcuts.

The Cypher is HARDCODED per shortcut (never generated by the LLM). After the
query runs, the LLM is used ONLY to write the final natural-language answer
from the real results — it never produces or modifies Cypher.
"""
import json
import logging

from agent.nodes.shortcuts import (
    help_text,
    parse_shortcut,
    render_cypher,
)
from agent.nodes.genui_builder import build_blocks
from agent.state import AgentState
from agent.trace_util import step
from graph.executor import run_read_query
from llm.router import get_provider
from llm.prompts.genui_summary_system import GENUI_SUMMARY_SYSTEM_PROMPT

logger = logging.getLogger(__name__)

_SYNTHESIS_DATA_CAP = 30

# ── Client dashboard ──────────────────────────────────────────────────────────

_CLIENT_Q_CLIENT = """
MATCH (c:Client {id: __ID__})<-[:APPLIES_TO_COMPANY]-(icc:InsuranceContractCompany)
MATCH (icc)-[:COMPANY_CONTRACT_UNDER_OFFER]->(o:InsuranceOffer)
WHERE o.active = true
RETURN c.name AS client, icc.name AS contrat, o.police AS police,
       o.name AS offre, toString(o.date_effet) AS date_effet
ORDER BY o.date_effet DESC, o.id DESC LIMIT 1
"""

_CLIENT_Q_STATS = """
MATCH (c:Client {id: __ID__})<-[:APPLIES_TO_COMPANY]-(icc:InsuranceContractCompany)
MATCH (icc)-[:COMPANY_CONTRACT_UNDER_OFFER]->(o:InsuranceOffer)
WHERE o.active = true
WITH o ORDER BY o.date_effet DESC, o.id DESC LIMIT 1
MATCH (ic:InsuranceContract)-[:CONTRACT_UNDER_OFFER]->(o)
WHERE ic.active = true
MATCH (a:Assure)<-[:COVERS]-(ic)
OPTIONAL MATCH (bs:BulletinSoin)-[:CREATED_FOR]->(a)
WHERE (bs)-[:FILED_UNDER_CONTRACT]->(ic)
WITH o, count(DISTINCT a.id) AS nb_assures, collect(DISTINCT bs) AS bss
UNWIND (case when bss = [] then [null] else bss end) AS bs
RETURN nb_assures,
       count(DISTINCT bs) AS nb_bs,
       coalesce(round(sum(bs.total_dep), 3), 0) AS total_depense,
       coalesce(round(sum(bs.total_pec), 3), 0) AS total_pec,
       case when sum(bs.total_dep) > 0
            then round(sum(bs.total_pec) / sum(bs.total_dep) * 100, 1)
            else 0 end AS taux_pec
"""

_CLIENT_Q_MONTHLY = """
MATCH (c:Client {id: __ID__})<-[:APPLIES_TO_COMPANY]-(icc:InsuranceContractCompany)
MATCH (icc)-[:COMPANY_CONTRACT_UNDER_OFFER]->(o:InsuranceOffer)
WHERE o.active = true
WITH o ORDER BY o.date_effet DESC, o.id DESC LIMIT 1
MATCH (ic:InsuranceContract)-[:CONTRACT_UNDER_OFFER]->(o)
WHERE ic.active = true
MATCH (a:Assure)<-[:COVERS]-(ic)
MATCH (bs:BulletinSoin)-[:CREATED_FOR]->(a)
MATCH (bs)-[:FILED_UNDER_CONTRACT]->(ic)
RETURN substring(toString(bs.validation_date), 0, 7) AS mois,
       count(DISTINCT bs.id) AS nb_bs,
       round(sum(bs.total_dep), 3) AS total_depense,
       round(sum(bs.total_pec), 3) AS total_pec
ORDER BY mois
"""

_CLIENT_Q_DISCIPLINE = """
MATCH (c:Client {id: __ID__})<-[:APPLIES_TO_COMPANY]-(icc:InsuranceContractCompany)
MATCH (icc)-[:COMPANY_CONTRACT_UNDER_OFFER]->(o:InsuranceOffer)
WHERE o.active = true
WITH o ORDER BY o.date_effet DESC, o.id DESC LIMIT 1
MATCH (ic:InsuranceContract)-[:CONTRACT_UNDER_OFFER]->(o)
WHERE ic.active = true
MATCH (a:Assure)<-[:COVERS]-(ic)
MATCH (bs:BulletinSoin)-[:CREATED_FOR]->(a)
MATCH (bs)-[:FILED_UNDER_CONTRACT]->(ic)
MATCH (p:BulletinSoinPrestation)-[:BELONGS_TO_BS]->(bs)
MATCH (det:BulletinSoinPrestationDetail)-[:CREATED_UNDER]->(p)
RETURN p.discipline AS discipline,
       count(DISTINCT bs.id) AS nb_bs,
       count(det.id) AS nb_actes,
       round(sum(det.montant_depense), 3) AS total_depense,
       round(sum(det.montant_pec), 3) AS total_pec
ORDER BY total_depense DESC
"""

_CLIENT_Q_PROVIDERS = """
MATCH (c:Client {id: __ID__})<-[:APPLIES_TO_COMPANY]-(icc:InsuranceContractCompany)
MATCH (icc)-[:COMPANY_CONTRACT_UNDER_OFFER]->(o:InsuranceOffer)
WHERE o.active = true
WITH o ORDER BY o.date_effet DESC, o.id DESC LIMIT 1
MATCH (ic:InsuranceContract)-[:CONTRACT_UNDER_OFFER]->(o)
WHERE ic.active = true
MATCH (a:Assure)<-[:COVERS]-(ic)
MATCH (bs:BulletinSoin)-[:CREATED_FOR]->(a)
MATCH (bs)-[:FILED_UNDER_CONTRACT]->(ic)
MATCH (p:BulletinSoinPrestation)-[:BELONGS_TO_BS]->(bs)
MATCH (phys:PhysicianSpecialty)<-[:PRESCRIBED_BY_SPECIALTY]-(p)
RETURN phys.name AS prestataire,
       count(DISTINCT bs.id) AS nb_bs,
       round(sum(p.montant_depense), 3) AS total_depense,
       round(sum(p.montant_pec), 3) AS total_pec
ORDER BY total_depense DESC LIMIT 10
"""

